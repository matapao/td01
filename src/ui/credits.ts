/**
 * The credits — who made what the game shows: the models, the icons (each game-icons.net author whose
 * icons are used, as CC BY asks), the fonts and the sounds. Shown in the Menu (Esc → Credits);
 * docs/CREDITS.md says the same at length.
 */
import { glyphCredits } from './glyphs.ts';

/** The faces (SIL Open Font License 1.1; the licences are in public/fonts/<family>/OFL.txt). */
export const FONT_CREDITS: { name: string; by: string; use: string }[] = [
  { name: 'Cinzel', by: 'Natanael Gama', use: 'titles' },
  { name: 'Alegreya', by: 'Juan Pablo del Peral, Huerta Tipográfica', use: 'text' },
  { name: 'Old Standard TT', by: 'Alexey Kryukov', use: 'the Steam Age boards' },
  { name: 'Courier Prime', by: 'Alan Dague-Greene', use: 'the Electric and Signal Age boards' },
  { name: 'Cutive', by: 'Vernon Adams', use: 'the words on the Electric and Signal Age boards' },
  { name: 'VT323', by: 'Peter Hull', use: 'the Electronic and Automated Age boards' },
  { name: 'Exo 2', by: 'Natanael Gama', use: 'the Space Age boards' },
];

const link = (url: string, text = url.replace(/^https?:\/\//, '').replace(/\/$/, '')) =>
  `<a href="${url}" target="_blank" rel="noopener">${text}</a>`;

/** The Credits section: a <summary> and its body (for a <details>). */
export function creditsHtml(): string {
  const icons = glyphCredits();
  const by = icons.filter((a) => a.licence !== 'CC0').map((a) => a.author);
  const free = icons.filter((a) => a.licence === 'CC0').map((a) => a.author);
  return `<summary>Credits</summary>
    <h4>Models and animations</h4>
    <p><b>KayKit</b> by Kay Lousberg — CC0 1.0 (public domain) — ${link('https://kaylousberg.com')}</p>
    <h4>Icons</h4>
    <p>Icons made by ${by.join(', ')}${free.length ? ` (CC BY 3.0) and ${free.join(', ')} (CC0)` : ' (CC BY 3.0)'}. Available on ${link('https://game-icons.net')}; recoloured for the HUD.</p>
    ${icons.map((a) => `<p><b>${a.author}</b> — ${a.licence}, game-icons.net <span class="cr-icons">· ${a.icons.join(', ')}</span></p>`).join('')}
    <h4>Fonts — SIL Open Font License 1.1</h4>
    ${FONT_CREDITS.map((f) => `<p><b>${f.name}</b> — ${f.by} <span class="cr-icons">· ${f.use}</span></p>`).join('')}
    <p class="cr-icons">Served from the game itself (no internet needed) — ${link('https://fonts.google.com', 'Google Fonts')}.</p>
    <h4>Sound</h4>
    <p>Original synthesized effects and ambience, generated by the game. No recorded audio is shipped or fetched.</p>
    <p>${link('./sound-credits.html', 'Audio source history')} records the removed third-party selections and their creators.</p>
    <p class="cr-icons">The rest — the terrain, water, sky and effects — is made in code.</p>`;
}
