const PATHDATA = /^[MmLlHhVvCcSsQqTtAaZz0-9eE.,\s+-]+$/;
/** @type {Record<string, string>} */
const out = {};
for (const id of ids) {
  const who = required(id.split('/')[0]);
  if (!AUTHORS[who]) throw new Error(`unknown author folder for ${id}`);
  const file = path.join(repo, `${id}.svg`);
  const svg = fs.readFileSync(file, 'utf8');
  if (/<(script|image|use|foreignObject|style)\b/i.test(svg)) throw new Error(`unexpected element in ${id}`);
  const ds = [...svg.matchAll(/\sd="([^"]*)"/g)]
    .map((m) => required(m[1]).trim())
    .filter((d) => d !== 'M0 0h512v512H0z');
  if (!ds.length) throw new Error(`no icon path in ${id}`);
  for (const d of ds) if (!PATHDATA.test(d)) throw new Error(`odd path data in ${id}`);
  // A later path's opening moveto is absolute even when written 'm': keep it so when joined.
  out[id] = ds.map((d, i) => (i && d[0] === 'm' ? `M${d.slice(1)}` : d)).join(' ');
}
const used = [...new Set(ids.map((id) => required(id.split('/')[0])))].sort();
const lines = [
  '// Generated by scripts/icons/build-glyphs.mjs from game-icons.net (github.com/game-icons/icons) — do not edit.',
  '// CC BY 3.0 (CC0 where marked); the authors are credited in the Menu (Credits) and docs/CREDITS.md.',
  '',
  '/** An icon: author folder / icon name, as on game-icons.net. */',
  `export type IconId =\n${ids.map((id) => `  | '${id}'`).join('\n')};`,
  '',
  '/** Their shapes: path data in a 512 × 512 square (the black background dropped). */',
  'export const ICON_PATHS: Record<IconId, string> = {',
  ...ids.map((id) => `  '${id}': '${out[id]}',`),
  '};',
  '',
  '/** Who drew them, and under which licence. */',
  "export const ICON_AUTHORS: Record<string, { name: string; url?: string; licence: 'CC BY 3.0' | 'CC0' }> = {",
  ...used.map((w) => {
    const [name, url, lic = 'CC BY 3.0'] = required(AUTHORS[w]);
    return `  '${w}': { name: '${name}',${url ? ` url: '${url}',` : ''} licence: '${lic}' },`;
  }),
  '};',
  '',
];
const dest = path.join(root, 'src/ui/glyph-data.ts');
fs.writeFileSync(dest, lines.join('\n'));
const bytes = Object.values(out).reduce((n, d) => n + d.length, 0);
console.log(
  `${ids.length} icons by ${used.join(', ')} → ${path.relative(root, dest)} (${(bytes / 1024).toFixed(1)} KB of path data)`,
);
