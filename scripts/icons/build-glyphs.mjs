/**
 * Copies the game-icons.net icons the game uses into src/ui/glyph-data.ts (their path data only).
 *   node scripts/icons/build-glyphs.mjs <game-icons checkout>
 * The checkout is github.com/game-icons/icons (an archive of it will do): one folder per author, each
 * icon a 512 × 512 SVG — a black square, then the white icon path. Which icons: every 'author/name'
 * string in src/ui/glyphs.ts. The files are read as data: only path data (checked to be just path
 * commands and numbers) is taken; the black square is dropped, so CSS colours the rest.
 * Licence: CC BY 3.0 (credit each author; done in the Menu and docs/CREDITS.md); Zeromancer and
 * Viscious Speed gave theirs as CC0.
 */
import fs from 'node:fs';
import path from 'node:path';
import { required } from '../../src/core/required.ts';

const repo = process.argv[2];
if (!repo || !fs.existsSync(path.join(repo, 'license.txt'))) {
  console.error('usage: node scripts/icons/build-glyphs.mjs <game-icons checkout (with license.txt)>');
  process.exit(1);
}
const root = path.resolve(path.dirname(new URL(import.meta.url).pathname), '../..');
const src = fs.readFileSync(path.join(root, 'src/ui/glyphs.ts'), 'utf8');
const ids = [...new Set([...src.matchAll(/'([a-z0-9-]+\/[a-z0-9-]+)'/g)].map((m) => required(m[1])))].sort();

/** The folders' authors, as license.txt names them (and where it says their icons are CC0). */
/** @type {Record<string, [string, (string | undefined)?, ('CC0' | 'CC BY 3.0')?]>} */
